#!/usr/bin/env python3
"""
Bundle generator for Lisan al-Dawat Lexicon & Spell Bank.
Combines seed data, normalization engine, storage engine, and app controller
into a single standalone IIFE script (js/app.bundle.js) to guarantee 100% offline
file:// execution without browser CORS restrictions.
"""

def build():
    with open('data/seed.js') as f:
        seed_content = f.read().replace('export const SEED_LEXICON =', 'const SEED_LEXICON =')

    with open('js/normalize.js') as f:
        norm_content = f.read()
        norm_content = norm_content.replace('export function ', 'function ').replace('export const ', 'const ')

    with open('js/storage.js') as f:
        storage_content = f.read()
        storage_content = storage_content.replace('export function ', 'function ').replace('export const ', 'const ')

    with open('js/app.js') as f:
        app_lines = f.readlines()
        filtered_app = []
        skip = False
        for line in app_lines:
            if line.strip().startswith('import '):
                skip = True
            if skip:
                if ';' in line:
                    skip = False
                continue
            filtered_app.append(line)
        app_content = ''.join(filtered_app)

    bundle = f'''/**
 * Lisan al-Dawat Lexicon & Spell Bank - Universal Offline Bundle
 * Automatically generated by build.py. Compatible with both local file:// and http:// protocols.
 */
(function() {{
  'use strict';

  // --- Seed Data ---
  {seed_content}

  // --- Normalization Engine ---
  {norm_content}

  // --- Storage Engine ---
  {storage_content}

  // --- Application Controller ---
  {app_content}
}})();
'''

    with open('js/app.bundle.js', 'w') as f:
        f.write(bundle)

    print('Built js/app.bundle.js successfully!')

if __name__ == '__main__':
    build()
